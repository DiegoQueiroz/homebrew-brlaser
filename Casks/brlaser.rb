# typed: strict
# frozen_string_literal: true

cask "brlaser" do
  version "6.2.8"
  sha256 "16dae855aa7fff0eef0c05398fab37678243d7d610fa5f9af0d3a2cc9bf08cb0"

  url "https://github.com/Owl-Maintain/brlaser/archive/refs/tags/v6.2.8.tar.gz"
  name "brlaser"
  desc "CUPS driver for Brother laser printers"
  homepage "https://github.com/Owl-Maintain/brlaser"

  livecheck do
    url "https://github.com/Owl-Maintain/brlaser"
    strategy :github_latest
  end

  depends_on formula: "cmake"

  preflight_steps do
    run "/opt/homebrew/bin/cmake",
        args: [
          "-S",
          "{{staged_path}}/brlaser-#{version}",
          "-B",
          "{{staged_path}}/build",
          "-DCMAKE_BUILD_TYPE=Release",
        ]
    run "/opt/homebrew/bin/cmake",
        args: ["--build", "{{staged_path}}/build"]
  end

  postflight_steps do
    # The upstream `cmake --install` also copies brlaser.drv into
    # /usr/share/cups, which SIP protects on macOS. Install only what macOS
    # uses instead: the CUPS filter and the generated PPDs.
    run "/bin/cp",
        args: [
          "{{staged_path}}/build/rastertobrlaser",
          "/usr/libexec/cups/filter/rastertobrlaser",
        ],
        sudo: true

    # brlaser.drv is generated by the cmake configure step into the build
    # directory (the tarball ships only brlaser.drv.in). Compile it into the
    # individual PPDs that System Settings > Printers & Scanners lists.
    run "/usr/bin/ppdc",
        args: [
          "-d",
          "{{staged_path}}/build/ppd",
          "{{staged_path}}/build/brlaser.drv",
        ]

    # Install the PPDs and record their names so uninstall removes exactly
    # what was installed. Upstream also emits non-br*.ppd names (fxp265d.ppd,
    # lnj2650d.ppd), so a fixed glob would leave files behind.
    run "/bin/sh",
        args: [
          "-c",
          "D=/Library/Printers/PPDs/Contents/Resources; S=\"{{staged_path}}/build/ppd\"; " \
          "/bin/mkdir -p \"$D\"; /bin/ls \"$S\" > \"$D/.brlaser-installed-ppds\"; " \
          "for f in \"$S\"/*.ppd; do /bin/cp \"$f\" \"$D/${f##*/}\"; done",
        ],
        sudo: true

    run "/bin/launchctl",
        args: ["stop", "org.cups.cupsd"],
        sudo: true
    run "/bin/launchctl",
        args: ["start", "org.cups.cupsd"],
        sudo: true
  end

  uninstall_preflight_steps do
    run "/bin/rm",
        args: ["-f", "/usr/libexec/cups/filter/rastertobrlaser"],
        sudo: true

    run "/bin/sh",
        args: [
          "-c",
          "D=/Library/Printers/PPDs/Contents/Resources; M=\"$D/.brlaser-installed-ppds\"; " \
          "if [ -f \"$M\" ]; then while read -r b; do /bin/rm -f \"$D/$b\"; done < \"$M\"; /bin/rm -f \"$M\"; " \
          "else /bin/rm -f \"$D\"/br*.ppd \"$D\"/fxp*.ppd \"$D\"/lnj*.ppd; fi",
        ],
        sudo: true

    run "/bin/launchctl",
        args: ["stop", "org.cups.cupsd"],
        sudo: true
    run "/bin/launchctl",
        args: ["start", "org.cups.cupsd"],
        sudo: true
  end

  caveats <<~EOS
    The brlaser CUPS driver has been installed and CUPS has been restarted.

    Add your Brother printer using System Settings > Printers & Scanners.
    Look for printer entries marked 'brlaser'.
  EOS
end
